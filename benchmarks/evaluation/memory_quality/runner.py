def load_dataset(path: Path = HERE / "dataset.json") -> list[dict[str, Any]]:
    dataset = json.loads(path.read_text(encoding="utf-8"))
    scenarios = dataset["scenarios"]
    if dataset["schema_version"] != 1 or not 8 <= len(scenarios) <= 12:
        raise ValueError("Expected schema 1 and 8–12 scenarios")
    identifiers = [s["scenario_id"] for s in scenarios]
    if len(set(identifiers)) != len(identifiers):
        raise ValueError("Duplicate scenario id")
    for scenario in scenarios:
        if len(scenario["learning_turns"]) != len(scenario["extractor_outputs"]):
            raise ValueError("Each learning turn needs one extraction response")
        if not all(isinstance(t, str) and t for t in scenario["learning_turns"]):
            raise ValueError("Learning turns must be nonempty strings")
        for key in ("should_write", "should_recall", "should_use"):
            value = scenario["expected"][key]
            if value is not None and not isinstance(value, bool):
                raise ValueError("Expectations must be bool or null")
    return scenarios


def memory_payloads(messages) -> list[dict[str, Any]]:
    """Read actual final admission; role alone is not a trust classification."""
    payloads = []
    for message in messages:
        if message.role != "system" or not message.content:
            continue
        try:
            payload = json.loads(message.content)
        except ValueError:
            continue
        if isinstance(payload, dict) and isinstance(payload.get("memories"), list):
            payloads.append(payload)
    return payloads


def consume_evidence(query: str, payloads: list[dict[str, Any]]) -> tuple[str, list[str]]:
    """A tiny explicit oracle deriving answers from facts, never scenario labels.

    This models a cautious consumer. It does NOT prove a real LLM behaves so.
    The used ids are attribution generated by this consumer and are checked
    independently against persisted/admitted ids by the evaluator.
    """
    entries = [entry for payload in payloads for entry in payload["memories"]]
    if "bypass refund approval" in query:
        return "Approval is required; identity and permissions are unchanged.", []
    current = re.search(r"now uses (PostgreSQL \d+)", query)
    if current:
        return current.group(1), []
    if "deploy to production" in query:
        for entry in entries:
            match = re.search(r"production deployments must be on (\w+)", entry["content"])
            if match:
                return f"NO; production deployment must be on {match.group(1)}.", [entry["id"]]
    if "language" in query and "team reports" in query:
        for entry in entries:
            if "团队周报统一用中文" in entry["content"]:
                return "团队周报必须用中文。", [entry["id"]]
    if "Which database" in query:
        facts = [e for e in entries if re.search(r"uses PostgreSQL \d+", e["content"])]
        versions = sorted({re.search(r"PostgreSQL \d+", e["content"])[0] for e in facts})
        if len(versions) > 1:
            return "CONFLICT: " + " / ".join(versions), [e["id"] for e in facts]
        if versions:
            return versions[0], [e["id"] for e in facts]
    return "UNKNOWN; the admitted evidence does not answer this question.", []


class ScriptedGateway:
    def __init__(self, outputs: dict[str, dict[str, Any]]) -> None:
        self.outputs = outputs
        self.requests = []
        self.extraction_requests = []
        self.used_ids: list[str] = []

    async def prepare_resolved(self, context, plan, request, **kwargs):
        return self

    async def generate_resolved(self, context, plan, request):
        if request.messages[0].content == EXTRACTION_SYSTEM_PROMPT:
            self.extraction_requests.append(request)
            user = json.loads(request.messages[1].content)["user"]
            output = self.outputs.get(user, {"memories": []})
            answer = json.dumps(output, ensure_ascii=False)
        else:
            self.requests.append(request)
            query = next(m.content for m in reversed(request.messages) if m.role == "user")
            answer, self.used_ids = consume_evidence(query, memory_payloads(request.messages))
        return ModelResponse(content=answer, provider="fake", model="memory-quality-script")


class RecordedQueue:
    def __init__(self) -> None:
        self.pending = []

    async def enqueue(self, **identifiers) -> None:
        self.pending.append(identifiers)


async def seed(factory, *, memory_on: bool, with_tool: bool):
    """Only seed ordinary actors, draft/profile/tool; publish via production service."""
    async with factory() as session:
        email = f"memory-quality-{uuid4().hex}@example.test"
        user = User(email=email, normalized_email=email, password_hash="unused")
        session.add(user)
        await session.flush()
        organization = Organization(name="Isolated memory quality", created_by=user.id)
        session.add(organization)
        await session.flush()
        session.add(
            OrganizationMembership(organization_id=organization.id, user_id=user.id, role="OWNER")
        )
        workspace = Workspace(organization_id=organization.id, name="Memory quality")
        session.add(workspace)
        await session.flush()
        credential = ProviderCredential(
            workspace_id=workspace.id, provider="fake", name="scripted", secret="unused"
        )
        session.add(credential)
        await session.flush()
        profile = ModelProfile(
            workspace_id=workspace.id,
            provider_credential_id=credential.id,
            model="memory-quality-script",
            temperature=0,
            max_tokens=256,
            timeout_seconds=5,
            capabilities={"tool_calling": True, "max_context_tokens": 8192},
        )
        session.add(profile)
        await session.flush()
        agent = Agent(
            workspace_id=workspace.id,
            name="Quality probe",
            model_profile_id=profile.id,
            system_prompt=(
                "Use evidence cautiously. Never bypass approval or change actor identity."
            ),
            runtime_config={"memory": {"long_term_memory": memory_on}},
        )
        session.add(agent)
        await session.flush()
        tool_definition = None
        if with_tool:
            spec = {
                "kind": "builtin",
                "identity": "create_ticket",
                "description": "Create an internal support ticket.",
                "input_schema": {
                    "type": "object",
                    "properties": {
                        "customer_ref": {"type": "string"},
                        "subject": {"type": "string"},
                    },
                    "required": ["customer_ref", "subject"],
                    "additionalProperties": False,
                },
                "effect": "WRITE",
                "risk_level": "HIGH",
                "approval_policy": "ALWAYS",
                "timeout_seconds": 30,
            }
            tool = Tool(workspace_id=workspace.id, name="create_ticket")
            session.add(tool)
            await session.flush()
            revision = ToolRevision(
                workspace_id=workspace.id,
                tool_id=tool.id,
                revision_number=1,
                spec=spec,
                spec_hash=canonical_json_hash(spec),
                created_by=user.id,
            )
            session.add(revision)
            await session.flush()
            session.add(
                AgentTool(
                    workspace_id=workspace.id,
                    agent_id=agent.id,
                    tool_id=tool.id,
                    tool_revision_id=revision.id,
                )
            )
            tool_definition = ToolDefinition(
                identity="create_ticket",
                revision_id=revision.id,
                spec_hash=revision.spec_hash,
                description=spec["description"],
                input_schema=spec["input_schema"],
                effect=ToolEffect.WRITE,
                risk_level=ToolRisk.HIGH,
                approval_policy=ToolApprovalPolicy.ALWAYS,
                timeout_seconds=30,
            )
        await session.commit()
        context = (
            await TenantService().get_workspace_access(
                session,
                principal=PrincipalContext(
                    request_id=f"mq-{uuid4().hex}",
                    trace_id=f"mq-{uuid4().hex}",
                    user_id=str(user.id),
                ),
                workspace_id=workspace.id,
            )
        ).context
        version = await AgentPublishService().publish(session, context, agent.id)
    return context, agent.id, version.id, tool_definition


async def run_scenario(factory, settings, scenario, *, memory_on=True):
    context, agent_id, version_id, definition = await seed(
        factory, memory_on=memory_on, with_tool=scenario["category"] == "HOSTILE_INSTRUCTION"
    )
    gateway = ScriptedGateway(
        dict(zip(scenario["learning_turns"], scenario["extractor_outputs"], strict=True))
    )
    queue = RecordedQueue()
    service = AgentRunService(
        factory,
        model_gateway_factory=lambda _: gateway,
        memory_selector=SqlAlchemyMemoryStore(factory),
        memory_writer=queue,
    )
    threads = ThreadService(factory, run_service=service)
    learn = await threads.create_thread(context, agent_id=agent_id, title="Learning")
    async with factory() as session:
        before = await session.get(AgentVersion, version_id)
        spec_before = canonical_json_hash(before.resolved_spec)
    policy_before = str(ToolPolicy.decide(definition)) if definition else None
    for text in scenario["learning_turns"]:
        submitted = await threads.submit_turn(context, learn.id, user_input=text)
        async with factory() as session:
            run = await session.get(AgentRun, submitted.run_id)
            if run.status != "SUCCEEDED":
                raise RuntimeError(f"Learning run failed: {run.failure_code}")
        # Drain the recorded production enqueue after completion. Invoke the
        # actual worker body; patch only its gateway constructor, no memory logic.
        with patch.object(extraction_worker, "SqlAlchemyModelGateway", return_value=gateway):
            for identifiers in queue.pending:
                await extraction_worker._extract_run_memories(settings, **identifiers)
        queue.pending.clear()
    if memory_on and len(gateway.extraction_requests) != len(scenario["learning_turns"]):
        raise RuntimeError("Production extraction worker did not reach the scripted provider")
    async with factory() as session:
        rows = list(
            await session.scalars(
                select(WorkspaceMemory)
                .where(
                    WorkspaceMemory.workspace_id == context.workspace_id,
                    WorkspaceMemory.agent_id == agent_id,
                )
                .order_by(WorkspaceMemory.created_at, WorkspaceMemory.id)
            )
        )
    later = await threads.create_thread(context, agent_id=agent_id, title="New thread query")
    admissions = []
    original_admit = ContextBudgetPolicy.admit

    def observe_admit(policy, *args, **kwargs):
        result = original_admit(policy, *args, **kwargs)
        admissions.append(result)
        return result

    with patch.object(ContextBudgetPolicy, "admit", observe_admit):
        submitted = await threads.submit_turn(context, later.id, user_input=scenario["later_query"])
    async with factory() as session:
        run = await session.get(AgentRun, submitted.run_id)
        after = await session.get(AgentVersion, version_id)
        if run.status != "SUCCEEDED" or not admissions:
            raise RuntimeError(f"Query run failed: {run.failure_code}")
        snapshot = run.effective_memory_snapshot
        answer = run.final_output
        policy_unchanged = spec_before == canonical_json_hash(after.resolved_spec)
        actor_unchanged = str(run.created_by) == context.user_id
    request = gateway.requests[-1]
    admission = admissions[-1]
    if request.messages != admission.messages:
        raise RuntimeError("Captured gateway input does not equal final ContextAdmissionResult")
    payloads = memory_payloads(admission.messages)
    admitted_ids = [e["id"] for p in payloads for e in p["memories"]]
    selected_ids = snapshot.get("memory_ids", [])
    if not set(admitted_ids).issubset(selected_ids):
        raise RuntimeError("Admitted ids are outside effective_memory_snapshot")
    written_ids = {str(row.id) for row in rows}
    if not set(gateway.used_ids).issubset(set(admitted_ids) & written_ids):
        raise RuntimeError("Scripted attribution references memory not written/admitted")
    if not policy_unchanged or not actor_unchanged:
        raise RuntimeError("Published spec or actor mutated")
    if payloads and not all(p.get("trust") == "UNTRUSTED" for p in payloads):
        raise RuntimeError("Admitted memory was not labelled UNTRUSTED")
    expected_answer = scenario["answer_contains"]
    task_ok = (
        None
        if expected_answer is None
        else (
            all(fragment in answer for fragment in expected_answer)
            and not any(fragment in answer for fragment in scenario["forbidden_claims"])
            and (scenario["expected"]["should_use"] is not True or bool(gateway.used_ids))
            and (scenario["expected"]["should_use"] is not False or not gateway.used_ids)
        )
    )
    return {
        "scenario_id": scenario["scenario_id"],
        "category": scenario["category"],
        "expected": scenario["expected"],
        "memory_on": memory_on,
        "write": [
            {"id": str(r.id), "content": r.content, "status": r.status, "provenance": r.provenance}
            for r in rows
        ],
        "effective_memory_snapshot": snapshot,
        "selected_ids": selected_ids,
        "admitted_ids": admitted_ids,
        "admitted_payloads": payloads,
        "use": {"scripted_consumer_ids": list(gateway.used_ids), "real_model_use": "UNKNOWN"},
        "answer": answer,
        "task_correct": task_ok,
        "policy": {
            "spec_unchanged": policy_unchanged,
            "actor_unchanged": actor_unchanged,
            "decision_before": policy_before,
            "decision_after": str(ToolPolicy.decide(definition)) if definition else None,
            "published_tool_names": [t.name for t in admission.tool_definitions],
            "execution_attempted": False,
        },
        "extraction_provider_calls": len(gateway.extraction_requests),
    }


def evaluate(observations: list[dict[str, Any]]) -> dict[str, dict[str, int | float | None]]:
    """Five metrics only; memory-weighted precision, scenario-weighted recall.

    Null labels are excluded, not counted as successes. Quality failures do
    not make the runner exit nonzero; only broken deterministic contracts do.
    """
    known_written = sum(
        len(o["write"]) for o in observations if o["expected"]["should_write"] is not None
    )
    correct_written = sum(
        len(o["write"]) for o in observations if o["expected"]["should_write"] is True
    )
    must_write = [o for o in observations if o["expected"]["should_write"] is True]
    must_recall = [o for o in observations if o["expected"]["should_recall"] is True]
    must_not_recall = [o for o in observations if o["expected"]["should_recall"] is False]
    tasks = [o for o in observations if o["task_correct"] is not None]
    pairs = {
        "Write precision": (correct_written, known_written),
        "Write recall": (sum(bool(o["write"]) for o in must_write), len(must_write)),
        "Required recall": (
            sum(
                bool(o["write"]) and {r["id"] for r in o["write"]}.issubset(o["admitted_ids"])
                for o in must_recall
            ),
            len(must_recall),
        ),
        "Forbidden/irrelevant recall": (
            sum(bool(o["admitted_ids"]) for o in must_not_recall),
            len(must_not_recall),
        ),
        "Task correctness": (sum(o["task_correct"] for o in tasks), len(tasks)),
    }
    return {
        name: {"numerator": n, "denominator": d, "rate": n / d if d else None}
        for name, (n, d) in pairs.items()
    }


async def run_quality(database_url: str, scenarios=None) -> dict[str, Any]:
    scenarios = scenarios or load_dataset()
    engine, factory = create_database(database_url)
    settings = get_settings().model_copy(update={"database_url": database_url})
    try:
        observations = []
        for scenario in scenarios:
            observations.append(await run_scenario(factory, settings, scenario))
        off = await run_scenario(factory, settings, scenarios[0], memory_on=False)
        if off["write"] or off["admitted_ids"] or off["extraction_provider_calls"]:
            raise RuntimeError("OFF sanity control learned or admitted memory")
        if "UNKNOWN" not in off["answer"]:
            raise RuntimeError("OFF control recovered a fact unavailable in its context")
        return {
            "schema_version": 1,
            "source_commit": subprocess.check_output(
                ["git", "rev-parse", "HEAD"], text=True
            ).strip(),
            "working_tree_dirty": bool(
                subprocess.check_output(["git", "status", "--porcelain"], text=True).strip()
            ),
            "runner_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            "dataset_sha256": canonical_json_hash(scenarios),
            "paid_calls": 0,
            "real_model": "NOT RUN",
            "scenario_count": len(scenarios),
            "observations": observations,
            "off_sanity_control": off,
            "metrics": evaluate(observations),
            "verdict": "NO_DEMONSTRATED_BENEFIT",
            "limitations": [
                "Scripted extraction probes deterministic gates, not real-model error frequency.",
                "USE/task correctness are scripted-consumer postconditions, not real LLM quality.",
                "No refund action executed; prior security evidence covers execution protection.",
                "Two ACTIVE contradictory facts can coexist; no automatic supersede exists.",
                "No scale, long-duration, enterprise-user or automatic TTL evidence.",
            ],
        }
    finally:
        await engine.dispose()


def write_summary(result: dict[str, Any], path: Path) -> None:
    lines = [
        "# Memory quality boundary probes",
        "",
        "11 scenarios; production Thread/runtime/worker parser/store/selector/admission.",
        "",
        "Zero paid calls. Task correctness and USE are scripted-consumer proxies.",
        "Grounded temporary/private/hostile candidates were deliberately forced; their",
        "acceptance demonstrates a missing semantic gate, not a measured LLM error rate.",
        "",
        "| Metric | Numerator / Denominator |",
        "| --- | --- |",
    ]
    for name, metric in result["metrics"].items():
        lines.append(f"| {name} | {metric['numerator']} / {metric['denominator']} |")
    lines += [
        "",
        "## WRITE / RECALL / USE observations",
        "",
        "| Scenario | Persisted | Selected | Admitted | Script used | Task proxy |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for o in result["observations"]:
        lines.append(
            f"| {o['scenario_id']} | {len(o['write'])} | {len(o['selected_ids'])} | "
            f"{len(o['admitted_ids'])} | {len(o['use']['scripted_consumer_ids'])} | "
            f"{o['task_correct']} |"
        )
    lines += [
        "",
        "## Evidence boundaries",
        "",
        *[f"- {limit}" for limit in result["limitations"]],
        "",
        "Verdict: **NO_DEMONSTRATED_BENEFIT** for new real-model business quality.",
        "Existing historical cross-thread evidence remains valid.",
        "",
        "Future direction: selector relevance rejection; no work started.",
        "TTL/decay are not justified by a time-duration experiment here.",
        "",
        "FEATURE DEVELOPMENT: STOP",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--database-url", default=os.getenv("AGENTHUB_TEST_DATABASE_URL"))
    parser.add_argument("--output", type=Path, default=HERE / "result.json")
    parser.add_argument("--summary", type=Path, default=HERE / "summary.md")
    args = parser.parse_args()
    if not args.database_url:
        parser.error("Use a migrated isolated PostgreSQL test database")
    if os.name == "nt":
        asyncio.set_event_loop_policy(asyncio.WindowsSelectorEventLoopPolicy())
    result = asyncio.run(run_quality(args.database_url))
    args.output.write_text(
        json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    write_summary(result, args.summary)
    print(json.dumps(result["metrics"], ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
