    ("baseline", "billing-multi_hop", 0),
    ("baseline", "billing-multi_hop", 1),
    ("baseline", "billing-multi_hop", 2),
    ("baseline", "delivery-multi_hop", 0),
    ("baseline", "delivery-multi_hop", 1),
    ("baseline", "delivery-multi_hop", 2),
    ("baseline", "subscription-multi_hop", 0),
    ("baseline", "subscription-multi_hop", 2),
